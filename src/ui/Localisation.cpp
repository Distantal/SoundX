void applyLanguage (const String& language)
{
    bool zh = language == "zh";
    if (language == "auto" || language.isEmpty())
        zh = SystemStats::getUserLanguage().startsWithIgnoreCase ("zh");

    if (zh)
        LocalisedStrings::setCurrentMappings (new LocalisedStrings (String::fromUTF8 (kChinese), false));
    else
        LocalisedStrings::setCurrentMappings (nullptr);
}

String currentLanguageSetting (PropertiesFile* props)
{
    return props != nullptr ? props->getValue ("language", "auto") : String ("auto");
}

void saveLanguageSetting (PropertiesFile* props, const String& language)
{
    if (props != nullptr)
    {
        props->setValue ("language", language);
        props->saveIfNeeded();
    }
}
